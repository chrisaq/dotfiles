#!/usr/bin/env python3
"""Render managed configuration from settings.json, rules.json and actions.json."""
import json
import os
from pathlib import Path
import re
from mailcore import ROOT, atomic_write, load_settings, helper_path


def quote(value):
    return '"' + str(value).replace('\\', '\\\\').replace('"', '\\"').replace('$', '\\$').replace('`', '\\`') + '"'


def render(write=True):
    """Return expected files; write=False is a side-effect-free drift check."""
    outputs = {}
    def emit(path, content, mode=0o600):
        outputs[Path(path)] = (content, mode)
        if write:
            atomic_write(path, content, mode)
    s = load_settings()
    state = Path(s['state'])
    data = Path(s['data'])
    cache = Path(s['cache'])
    database = data / 'notmuch'
    helper = helper_path()
    channel = s.get('channel_name', 'primary')
    account = s.get('account_name', 'primary')
    # Render machine-specific paths from a public template.
    emit(ROOT / 'mailcap', (ROOT / 'mailcap.in').read_text().replace('@MAILCTL@', str(helper)))
    integrations = Path(s.get('integrations', ROOT / 'integrations'))
    for directory in (state, data, cache, cache / 'headers', cache / 'bodies',
                      data / 'contacts/addressbook', database, cache / 'html'):
        if write:
            directory.mkdir(parents=True, exist_ok=True, mode=0o700)
    # First sync indexes before transport; an empty Maildir must already exist.
    for part in ('cur', 'new', 'tmp'):
        if write:
            (Path(s['mail_root']) / part).mkdir(parents=True, exist_ok=True, mode=0o700)
    emit(integrations / 'gopass.conf', '[mounts]\n path = ' + s['password_store'] + '\n')
    emit(integrations / 'notmuch/config', f'''[database]
path={database}
mail_root={s['mail_root']}
hook_dir={integrations}/notmuch/hooks
[user]
name={s['realname']}
primary_email={s['primary_email']}
other_email={';'.join(s['aliases'])};
[new]
tags=new
ignore=.mbsyncstate;.uidvalidity;.isyncuidmap.db
[search]
exclude_tags=spam;trash
[maildir]
synchronize_flags=true
[index]
header.ListId=List-Id
header.ListUnsubscribe=List-Unsubscribe
''')
    emit(integrations / 'notmuch/hooks/post-new', f'#!/bin/sh\nexec "{helper}" after-new\n', 0o700)
    rules = json.loads((ROOT / 'rules.json').read_text())
    afew = ['# Generated by build-config.py; edit rules.json.\n[global]\n']
    for n, rule in enumerate(rules):
        klass = 'HeaderMatchingFilter' if 'header' in rule else 'Filter'
        header = f"header = {rule['header']}\npattern = {rule['pattern']}\n" if 'header' in rule else ''
        query = '' if rule['query'] == '*' else f"({rule['query']}) and "
        afew.append(f"[{klass}.{n}]\nquery = {query}not tag:spam and not tag:trash\n{header}tags = +{rule['tag']}\nmessage = {rule['description']}\n")
    emit(integrations / 'afew/config', '\n'.join(afew))
    emit(integrations / 'mbsyncrc', f'''# Managed mail channel; preserve the original bidirectional expunge policy.
IMAPStore {channel}-remote
Host {s['imap_host']}
Port 993
User {s['imap_username']}
PassCmd "{helper} credential mail"
AuthMechs LOGIN
SSLType IMAPS
CertificateFile {s['tls_ca_file']}

MaildirStore {channel}-local
Subfolders Maildir++
Inbox {s['mail_root']}/

Channel {channel}
Far :{channel}-remote:
Near :{channel}-local:
Patterns *
Create Both
Expunge Both
Sync All
SyncState *
''')
    emit(integrations / 'msmtprc', f'''defaults
auth on
tls on
tls_starttls on
tls_trust_file {s['tls_ca_file']}
timeout 30

account {account}
host {s['smtp_host']}
port {s['smtp_port']}
from {s['primary_email']}
allow_from_override on
user {s['imap_username']}
passwordeval "{helper} credential mail"

account default : {account}
''')
    emit(integrations / 'khard/khard.conf', f'''[addressbooks]
[[contacts]]
path = {data}/contacts/addressbook
[general]
default_action = list
editor = vim
merge_editor = vimdiff
''')
    emit(integrations / 'vdirsyncer/config', f'''[general]
status_path = "{state}/vdirsyncer"
[pair contacts]
a = "contacts_local"
b = "contacts_remote"
collections = null
partial_sync = "revert"
[storage contacts_local]
type = "filesystem"
path = "{data}/contacts/addressbook"
fileext = ".vcf"
[storage contacts_remote]
type = "carddav"
url = "{s['contacts_url']}"
username = "{s['contacts_username']}"
password.fetch = ["command", "{helper}", "credential", "contacts"]
read_only = true
''')
    emit(ROOT / 'accounts/primary.muttrc', f'''# Generated; change settings.json and run cq_mailctl render.
set realname = {quote(s['realname'])}
set from = {quote(s['primary_email'])}
set sendmail = {quote(f"msmtp --file={integrations}/msmtprc -a {account}")}
alias me {s['realname']} <{s['primary_email']}>
set folder = {quote(s['mail_root'] + '/')}
set spool_file = {quote(f"notmuch://{database}?query=tag:inbox")}
set postponed = +.Drafts
set trash = +.Trash
set record = +.Sent
set mbox_type = Maildir
set hostname = {quote(s['primary_email'].rsplit('@', 1)[-1])}
set mask = ".*"
set header_cache = {quote(str(cache / 'headers'))}
set message_cache_dir = {quote(str(cache / 'bodies'))}
alternates {quote('^(' + '|'.join(re.escape(x) for x in [s['primary_email'], *s['aliases']]) + ')$')}
mailboxes {quote(s['mail_root'] + '/')} {quote(s['mail_root'] + '/.Drafts')} {quote(s['mail_root'] + '/.Sent')} {quote(s['mail_root'] + '/.Archive')} {quote(s['mail_root'] + '/.Spam')} {quote(s['mail_root'] + '/.Trash')}
''')
    views = [('Inbox', 'tag:inbox'), ('Unread Inbox', 'tag:inbox and tag:unread'),
             ('Flagged', 'tag:flagged'), ('Sent', 'tag:sent'),
             ('Archive', 'not tag:inbox and not tag:sent and not tag:draft'),
             ('All mail', '*')]
    views += [(rule['tag'].split('/')[1].title(), 'tag:' + rule['tag']) for rule in rules]
    emit(ROOT / 'views.muttrc', '# Generated saved searches\n' + '\n'.join(
        f'named-mailboxes {quote(name)} {quote(f"notmuch://{database}?query={query}")}' for name, query in views) + '\n')
    emit(ROOT / 'integration.muttrc', f'''# Generated from settings.json.
set nm_config_file = {quote(str(integrations / 'notmuch/config'))}
set nm_default_url = {quote(f'notmuch://{database}')}
set nm_query_type = messages
set nm_exclude_tags = "spam,trash"
set nm_record = yes
set nm_record_tags = "sent,-inbox,-new"
set hidden_tags = "unread,draft,flagged,replied,passed,new,history-pending,inbox,sent"
set query_command = {quote(str(helper) + ' query %s')}
set print_command = {quote(str(helper) + ' pdf')}
''')
    actions = json.loads((ROOT / 'actions.json').read_text())
    lines = ['# Generated from actions.json. Do not edit.',
             'bind index,pager i noop', 'bind index,pager g noop',
             'bind index,pager M noop', 'bind index,pager C noop',
             'bind index \\Cf noop', 'bind editor <Space> noop']
    seen = set()
    for action in actions:
        for context in action['contexts']:
            identity = (context, action['key'])
            if identity in seen:
                raise ValueError(f'Duplicate action: {identity}')
            seen.add(identity)
        contexts = ','.join(action['contexts'])
        key = '"' + action['key'].replace('"', '\\"') + '"'
        if action['kind'] == 'function':
            lines.append(f"bind {contexts} {key} {action['action']}")
        else:
            # Resolve the default database path from the registry when configured differently.
            command = action['action'].replace('@DATABASE@', str(database))
            command = command.replace('@MAILCTL@', str(helper))
            command = command.replace('@ATTACHMENTS@', s['attachments'])
            lines.append(f"macro {contexts} {key} {quote(command)} {quote(action['description'])}")
    emit(ROOT / 'bindings.muttrc', '\n'.join(lines) + '\n')
    emit(ROOT / 'KEYBINDINGS.md', '# Managed keybindings\n\nGenerated from `actions.json`; use F1 in NeoMutt to search and run them.\n\n| Context | Key | Action |\n| --- | --- | --- |\n' + '\n'.join(
        '| ' + ', '.join(a['contexts']) + ' | `' + a['key'] + '` | ' + a['description'] + ' |' for a in actions) + '\n')
    for component, command in [('mail', 'sync'), ('contacts', 'contacts sync')]:
        emit(ROOT / f'systemd/cq-{component}.service', f'''[Unit]
Description=Personal {component} sync
Wants=network-online.target
After=network-online.target

[Service]
Type=oneshot
Environment=CQ_MAIL_SCHEDULED=1
{('Environment=' + quote('CQ_MAIL_CONFIG=' + str(Path(os.environ['CQ_MAIL_CONFIG']).expanduser().resolve()))) if os.environ.get('CQ_MAIL_CONFIG') else ''}
Environment="CQ_MAIL_DATA={s['data']}"
Environment="CQ_MAIL_STATE={s['state']}"
Environment="CQ_MAIL_CACHE={s['cache']}"
Environment="CQ_MAIL_RUNTIME={s['runtime']}"
Environment=GNUPGHOME={s['gnupghome']}
Environment=PASSWORD_STORE_DIR={s['password_store']}
ExecStart={helper} {command}
SuccessExitStatus=75
TimeoutStartSec=35min
UMask=0077
''')
        emit(ROOT / f'systemd/cq-{component}.timer', f'''[Unit]
Description=Sync personal mail {component} every five minutes without pinentry

[Timer]
OnStartupSec=2min
OnUnitInactiveSec=5min
RandomizedDelaySec=15s
Unit=cq-{component}.service

[Install]
WantedBy=timers.target
''')

    return outputs


if __name__ == '__main__':
    render()
